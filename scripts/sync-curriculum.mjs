import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { renderRuntimeModule } from "./curriculum-codegen.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const siblingRoot = resolve(root, "../infraenv-curriculum");
const source = resolve(siblingRoot, "dist/profiles/runtime/catalog.json");
const target = resolve(root, "vendor/curriculum/catalog.json");
const metadataTarget = resolve(root, "vendor/curriculum/checksum.json");
const generatedTarget = resolve(root, "packages/simulation/src/generated/curriculum.ts");
const contentLicenseTarget = resolve(root, "vendor/curriculum/LICENSE-CONTENT");
const attributionTarget = resolve(root, "vendor/curriculum/ATTRIBUTION.md");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");

let parsed;
try {
  parsed = JSON.parse(await readFile(source, "utf8"));
} catch (error) {
  console.error(`Cannot read compiled curriculum profile at ${source}.`);
  console.error("Build the sibling infraenv-curriculum repository first; source content is never read directly by this consumer.");
  throw error;
}

if (!parsed.manifest?.integrity || typeof parsed.manifest.integrity !== "object") throw new Error("Compiled curriculum profile has no source-integrity manifest.");
for (const [relativePath, expected] of Object.entries(parsed.manifest.integrity)) {
  const bytes = await readFile(resolve(siblingRoot, "content", relativePath));
  const actual = `sha256-${sha256(bytes)}`;
  if (actual !== expected) throw new Error(`Curriculum source integrity mismatch for ${relativePath}: expected ${expected}, got ${actual}.`);
}

const contentLicense = await readFile(resolve(siblingRoot, "LICENSE-CONTENT"));
const attribution = await readFile(resolve(siblingRoot, "content/LICENSE.md"));
const canonical = `${JSON.stringify(parsed, null, 2)}\n`;
const digest = sha256(canonical);
const generated = renderRuntimeModule(parsed);
const metadata = {
  _generated: "DO NOT EDIT — generated by scripts/sync-curriculum.mjs",
  source: "../infraenv-curriculum/dist/profiles/runtime/catalog.json",
  algorithm: "sha256",
  digest,
  contentVersion: parsed.manifest.contentVersion,
  manifestIntegrityVerified: Object.keys(parsed.manifest.integrity).length,
  generatedModuleDigest: sha256(generated),
  contentLicenseDigest: sha256(contentLicense),
  attributionDigest: sha256(attribution)
};

for (const path of [target, generatedTarget, contentLicenseTarget, attributionTarget]) await mkdir(dirname(path), { recursive: true });
await writeFile(target, canonical, "utf8");
await writeFile(generatedTarget, generated, "utf8");
await writeFile(contentLicenseTarget, contentLicense);
await writeFile(attributionTarget, attribution);
await writeFile(metadataTarget, `${JSON.stringify(metadata, null, 2)}\n`, "utf8");
console.log(`Synced runtime curriculum ${metadata.contentVersion}; verified ${metadata.manifestIntegrityVerified} source assets (${digest.slice(0, 12)}…).`);
