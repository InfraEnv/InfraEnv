import { createHash, randomUUID } from "node:crypto";
import { mkdir, readFile, rename, rm, writeFile } from "node:fs/promises";
import { dirname, isAbsolute, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { renderRuntimeModule } from "./curriculum-codegen.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const profileSource = resolve(root, "../infraenv-curriculum/dist/profiles/runtime");
const profileManifestSource = resolve(profileSource, "profile-manifest.json");
const vendorRoot = resolve(root, "vendor");
const target = resolve(vendorRoot, "curriculum");
const generatedTarget = resolve(root, "packages/simulation/src/generated/curriculum.ts");
const sha256 = (value) => createHash("sha256").update(value).digest("hex");

function safeArtifactPath(path) {
  if (!path || isAbsolute(path) || path.includes("\\") || path.split("/").some((part) => !part || part === "." || part === "..")) throw new Error(`Unsafe profile artifact path: ${path}.`);
  return path;
}

let profileManifestBytes;
let profileManifest;
try {
  profileManifestBytes = await readFile(profileManifestSource);
  profileManifest = JSON.parse(profileManifestBytes.toString("utf8"));
} catch (error) {
  console.error(`Cannot read compiled curriculum profile manifest at ${profileManifestSource}.`);
  console.error("Build the sibling infraenv-curriculum repository first; this consumer never reads source content directly.");
  throw error;
}

if (profileManifest.profile !== "runtime" || profileManifest.schemaVersion !== "2.0.0") throw new Error("Unsupported curriculum runtime profile manifest.");
if (!profileManifest.artifacts || typeof profileManifest.artifacts !== "object") throw new Error("Runtime profile manifest has no artifact integrity map.");

const artifacts = new Map();
for (const [relativePath, expected] of Object.entries(profileManifest.artifacts)) {
  safeArtifactPath(relativePath);
  const bytes = await readFile(resolve(profileSource, ...relativePath.split("/")));
  const actual = `sha256-${sha256(bytes)}`;
  if (actual !== expected) throw new Error(`Compiled profile artifact mismatch for ${relativePath}: expected ${expected}, got ${actual}.`);
  artifacts.set(relativePath, bytes);
}

const catalogBytes = artifacts.get("catalog.json");
if (!catalogBytes) throw new Error("Runtime profile does not include catalog.json.");
if (`sha256-${sha256(catalogBytes)}` !== profileManifest.catalogSha256) throw new Error("catalogSha256 does not match the verified catalog artifact.");
const parsed = JSON.parse(catalogBytes.toString("utf8"));
if (parsed.manifest?.contentVersion !== profileManifest.contentVersion) throw new Error("Catalog and profile manifest contentVersion differ.");
const generated = renderRuntimeModule(parsed);
const metadata = {
  _generated: "DO NOT EDIT — generated by scripts/sync-curriculum.mjs",
  source: "../infraenv-curriculum/dist/profiles/runtime/profile-manifest.json",
  algorithm: "sha256",
  digest: sha256(catalogBytes),
  contentVersion: profileManifest.contentVersion,
  profileSchemaVersion: profileManifest.schemaVersion,
  verifiedArtifacts: Object.keys(profileManifest.artifacts).length,
  profileManifestDigest: sha256(profileManifestBytes),
  generatedModuleDigest: sha256(generated),
  contentLicenseDigest: sha256(artifacts.get("LICENSE-CONTENT") ?? new Uint8Array()),
  attributionDigest: sha256(artifacts.get("ATTRIBUTION.md") ?? new Uint8Array())
};

await mkdir(vendorRoot, { recursive: true });
const staging = resolve(vendorRoot, `.curriculum-stage-${randomUUID()}`);
const backup = resolve(vendorRoot, `.curriculum-backup-${randomUUID()}`);
const generatedTemporary = `${generatedTarget}.${randomUUID()}.tmp`;
await mkdir(staging, { recursive: true });
for (const [relativePath, bytes] of artifacts) {
  const destination = resolve(staging, ...relativePath.split("/"));
  const relation = destination.slice(staging.length + 1);
  if (!relation || relation.startsWith(`..${sep}`)) throw new Error(`Artifact escaped staging directory: ${relativePath}.`);
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, bytes);
}
await writeFile(resolve(staging, "profile-manifest.json"), profileManifestBytes);
await writeFile(resolve(staging, "checksum.json"), `${JSON.stringify(metadata, null, 2)}\n`, "utf8");
await mkdir(dirname(generatedTarget), { recursive: true });
await writeFile(generatedTemporary, generated, "utf8");

let movedExisting = false;
try {
  try { await rename(target, backup); movedExisting = true; } catch (error) { if (error.code !== "ENOENT") throw error; }
  await rename(staging, target);
  await rename(generatedTemporary, generatedTarget);
  if (movedExisting) await rm(backup, { recursive: true, force: true });
} catch (error) {
  await rm(staging, { recursive: true, force: true });
  await rm(generatedTemporary, { force: true });
  if (movedExisting) {
    await rm(target, { recursive: true, force: true });
    await rename(backup, target);
  }
  throw error;
}

console.log(`Synced runtime curriculum ${metadata.contentVersion}; verified ${metadata.verifiedArtifacts} compiled artifacts (${metadata.digest.slice(0, 12)}…).`);
