import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createProgram } from "../packages/cli/dist/index.js";

const outputPath = resolve("docs/cli-reference.md");
const program = createProgram();

function commandPath(command) {
  const values = [];
  let current = command;
  while (current) {
    values.unshift(current.name());
    current = current.parent;
  }
  return values.join(" ");
}

function collect(command, output = []) {
  output.push(command);
  for (const child of command.commands) {
    if (child.name() !== "help") collect(child, output);
  }
  return output;
}

const sections = collect(program).map((command) => {
  const path = commandPath(command);
  return `## ${path}\n\n\`\`\`text\n${command.helpInformation().trimEnd()}\n\`\`\``;
});

const content = `# CLI Reference\n\n<!-- GENERATED by scripts/generate-cli-reference.mjs. DO NOT EDIT. -->\n\nThis reference is generated from Commander metadata for InfraEnv \`0.2.0-alpha.0\`. A listed command may still require a capability advertised by the active Supervisor. In particular, general Playground PTY attach, external S3 connect/load, and generic fault mutation are unavailable in this alpha and fail explicitly.\n\n${sections.join("\n\n")}\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current.replaceAll("\r\n", "\n") !== content) {
    console.error("docs/cli-reference.md is stale. Run `npm run docs:generate` after building the CLI.");
    process.exit(1);
  }
  console.log("Generated CLI reference is current.");
} else {
  await writeFile(outputPath, content, "utf8");
  console.log(`Generated ${outputPath}.`);
}
